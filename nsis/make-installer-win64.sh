#!/bin/bash
#
# make-installer-win64.sh - build the 64-bit NSIS installer from the folder
# made by make-dist-win64.sh.
#
#   nsis/make-installer-win64.sh DIST_DIR [OUT_DIR] [makensis options...]
#
#   DIST_DIR  folder made by make-dist-win64.sh
#   OUT_DIR   where Zylpheed-<version>-x64_setup.exe is written (default:
#             the parent directory of DIST_DIR)
#   further arguments go to makensis, e.g. -DWITH_TEST_PLUGIN or
#   -DPRODUCT_VERSION=3.8.0
#
# Needs makensis on PATH (MSYS2: pacman -S mingw-w64-ucrt-x86_64-nsis).
# Generates the uninstaller's file list from DIST_DIR, so the uninstaller
# removes exactly the installed files and no others.

set -e

NSISDIR_SRC=$(cd "$(dirname "$0")" && pwd)
[ -n "$1" ] || { echo "usage: $0 DIST_DIR [OUT_DIR] [makensis options]" >&2; exit 1; }
DIST=$(cd "$1" && pwd)
OUT=${2:-$(dirname "$DIST")}
shift; [ $# -gt 0 ] && shift
OUT=$(cd "$OUT" && pwd)
[ -f "$DIST/zylpheed.exe" ] || { echo "$DIST/zylpheed.exe not found" >&2; exit 1; }
command -v makensis >/dev/null || { echo "makensis not found" >&2; exit 1; }

LIST=$(mktemp --suffix=.nsh)
trap 'rm -f "$LIST"' EXIT

# Files of the main section: everything except plugins\ (own sections),
# run-test.bat, zylpheed.ini (portable mode) and the profile folders
# (excluded by zylpheed.nsi as well).
{
	echo "; generated by make-installer-win64.sh from $DIST"
	(cd "$DIST" && find . -type f ! -path './plugins/*' ! -path './profile/*' \
		! -path './profiles/*' ! -name run-test.bat ! -name zylpheed.ini | sed 's|^\./||' | sort) |
	while IFS= read -r f; do
		printf '  Delete "$INSTDIR\\%s"\n' "${f//\//\\}"
	done
	# directories, deepest first; RMDir without /r only removes empty ones
	(cd "$DIST" && find . -mindepth 1 -type d ! -path './plugins' \
		! -path './plugins/*' ! -path './profile' ! -path './profile/*' \
		! -path './profiles' ! -path './profiles/*' |
		sed 's|^\./||' | awk -F/ '{ print NF "\t" $0 }' | sort -rn | cut -f2-) |
	while IFS= read -r d; do
		printf '  RMDir "$INSTDIR\\%s"\n' "${d//\//\\}"
	done
} | sed 's/$/\r/' > "$LIST"

echo "make-installer-win64: $(grep -c Delete "$LIST") files in the uninstall list"

cd "$NSISDIR_SRC"
# -D options with Windows paths: MSYS would rewrite a leading "/".
makensis -V3 \
	-DDIST_DIR="$(cygpath -w "$DIST")" \
	-DUNINST_LIST="$(cygpath -w "$LIST")" \
	-DOUTDIR="$(cygpath -w "$OUT")" \
	"$@" zylpheed.nsi
